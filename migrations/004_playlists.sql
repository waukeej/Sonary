BEGIN;
CREATE TABLE IF NOT EXISTS playlists (
    playlist_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users(user_id),
    title varchar(255) NOT NULL CHECK (length(trim(title)) > 0),
    description text NOT NULL DEFAULT '',
    privacy varchar(7) NOT NULL DEFAULT 'private' CHECK (privacy IN ('private','public')),
    cover_filename varchar(40),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS playlists_owner_idx ON playlists(user_id);
CREATE TABLE IF NOT EXISTS playlist_tracks (
    playlist_id bigint NOT NULL REFERENCES playlists(playlist_id) ON DELETE CASCADE,
    track_id integer NOT NULL REFERENCES tracks(track_id) ON DELETE CASCADE,
    PRIMARY KEY (playlist_id, track_id)
);
CREATE INDEX IF NOT EXISTS playlist_tracks_track_idx ON playlist_tracks(track_id);
COMMIT;
