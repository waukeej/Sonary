-- Includes migrations 001 through 005. No accounts, uploads or sequence state.
BEGIN;

CREATE TABLE users (
    user_id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    email varchar(255) NOT NULL CONSTRAINT users_email_key UNIQUE,
    username varchar(12) NOT NULL CONSTRAINT users_username_key UNIQUE,
    password_hash varchar(255) NOT NULL,
    display_name varchar(100) NOT NULL DEFAULT '',
    bio varchar(1000) NOT NULL DEFAULT '',
    city varchar(100) NOT NULL DEFAULT '',
    avatar_filename varchar(40),
    profile_visibility varchar(7) NOT NULL DEFAULT 'public',
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_username_length CHECK (char_length(username) BETWEEN 3 AND 12),
    CONSTRAINT users_profile_visibility_check CHECK (profile_visibility IN ('public','private'))
);
CREATE UNIQUE INDEX users_username_ci_unique ON users(lower(username));
CREATE UNIQUE INDEX users_email_ci_unique ON users(lower(email));

CREATE TABLE tracks (
    track_id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users(user_id),
    title varchar(255) NOT NULL,
    artist varchar(255) NOT NULL DEFAULT '',
    short_description text NOT NULL DEFAULT '',
    full_description text NOT NULL DEFAULT '',
    rating smallint NOT NULL DEFAULT 0 CHECK (rating BETWEEN 0 AND 10),
    mood varchar(12) NOT NULL DEFAULT '' CHECK (mood IN ('','happy','calm','sad','energetic')),
    entry_date date,
    entry_time time,
    audio_filename varchar(40),
    cover_filename varchar(40),
    duration_seconds double precision CHECK (duration_seconds >= 0),
    privacy varchar(7) NOT NULL DEFAULT 'private' CHECK (privacy IN ('public','private')),
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX tracks_owner_date_idx ON tracks(user_id,entry_date DESC,track_id DESC);

CREATE TABLE playlists (
    playlist_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users(user_id),
    title varchar(255) NOT NULL CHECK (length(trim(title)) > 0),
    description text NOT NULL DEFAULT '',
    privacy varchar(7) NOT NULL DEFAULT 'private' CHECK (privacy IN ('private','public')),
    cover_filename varchar(40),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    system_key varchar(32)
);
CREATE INDEX playlists_owner_idx ON playlists(user_id);
CREATE UNIQUE INDEX playlists_user_system_key ON playlists(user_id,system_key);

CREATE TABLE playlist_tracks (
    playlist_id bigint NOT NULL REFERENCES playlists(playlist_id) ON DELETE CASCADE,
    track_id integer NOT NULL REFERENCES tracks(track_id) ON DELETE CASCADE,
    PRIMARY KEY (playlist_id,track_id)
);
CREATE INDEX playlist_tracks_track_idx ON playlist_tracks(track_id);

CREATE TABLE track_likes (
    user_id integer NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    track_id integer NOT NULL REFERENCES tracks(track_id) ON DELETE CASCADE,
    PRIMARY KEY (user_id,track_id)
);
COMMIT;

